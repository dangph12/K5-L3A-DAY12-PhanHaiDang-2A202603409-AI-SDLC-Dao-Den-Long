import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {Game,idle} from '../dist-cli/game.js'
const {tuning:t,contract_version}=JSON.parse(readFileSync('game.contract.json','utf8'))
// CP4 raises the envelope to 1.3 for bench/soak commands; the v1.2 tuning and game rules stay unchanged.
assert.equal(contract_version,'1.3')
const quiet={random_motes:false,random_shades:false,random_drifters:false,wind_enabled:false}
const press=game=>game.step({...idle(),interact:true})
const g=new Game(t,1,{...quiet,player:{carried:10},lanterns:[{id:'L1',pos:[0,0,0]}]},1)
press(g)
assert.equal(g.lanterns[0].lit,true)
assert.equal(g.capacity,12)
assert.equal(g.state,'playing')
assert.equal(g.score,150)
g.step(idle())
g.player.carried=1
press(g)
assert.equal(g.events.find(e=>e.name==='refuel')?.data.amount,1)
assert.equal(g.score,155)
const faded=new Game(t,1,{...quiet,lanterns:[{id:'L1',lit:true,fuel:1/60,pos:[0,0,0]}]},1)
faded.step(idle())
assert.equal(faded.lanterns[0].lit,false)
assert.equal(faded.events.find(e=>e.name==='lantern_out')?.tick,1)
faded.player.carried=5
faded.step({...idle(),interact:true})
assert.equal(faded.lanterns[0].lit,true)
assert.equal(faded.events.find(e=>e.name==='lantern_lit')?.data.relight,true)
const dawn=new Game(t,1,{...quiet,time_left_s:1/60,lanterns:[{id:'L1',lit:true},{id:'L2',lit:true},{id:'L3',lit:true}]},1)
dawn.step(idle())
assert.equal(dawn.state,'won')
assert.equal(dawn.events.find(e=>e.name==='game_over')?.data.reason,'dawn_survived')
console.log('PASS CP3 fuel, refuel, relight, capacity and dawn')
const drain=new Game(t,1,{...quiet,lanterns:[{id:'L1',pos:[0,0,0],lit:true,fuel:29}],shades:[{id:'S1',pos:[0,.8,1],state:'drain',target_lantern_id:'L1'}],player:{pos:[15,0,0]}},1)
for(let i=0;i<60;i++)drain.step(idle())
assert.equal(drain.shades[0].state,'drain')
assert.equal(drain.lanterns[0].fuelUnits,23*60)
assert.deepEqual(drain.events.find(e=>e.name==='fuel_drain')?.data,{lantern_id:'L1',shade_id:'S1',fuel:23})
drain.player.pos=[0,0,0]
drain.player.carried=8
drain.step({...idle(),interact:true})
assert.ok(drain.lanterns[0].fuelUnits/60>=30)
assert.notEqual(drain.shades[0].state,'drain')
const low=new Game(t,1,{...quiet,lanterns:[{id:'L1',pos:[0,0,0],lit:true,fuel:29}],shades:[{id:'S1',pos:[0,.8,0]}]},1)
low.step(idle())
assert.equal(low.events.find(e=>e.name==='player_hit')?.data.by,'shade')
const threshold=new Game(t,1,{...quiet,lanterns:[{id:'L1',pos:[0,0,0],lit:true,fuel:30+1/60}],shades:[{id:'S1',pos:[0,.8,0]}]},1)
threshold.step(idle())
assert.equal(threshold.events.find(e=>e.name==='player_hit'),undefined)
const dying=new Game(t,1,{...quiet,time_left_s:1/60,player:{flames:1,pos:[42,-11,0]},lanterns:[{id:'L1',lit:true},{id:'L2',lit:true},{id:'L3',lit:true}]},1)
dying.step(idle())
assert.equal(dying.events.find(e=>e.name==='game_over')?.data.reason,'no_flames')
console.log('PASS CP3 drain, sanctuary threshold and terminal priority')
const seeded=new Game(t,1,{...quiet,player:{successful_lights:5,carried:19},lanterns:[{id:'L1',lit:true,ever_lit:true,fuel:30,relit_count:2}]},1)
assert.equal(seeded.capacity,20)
assert.deepEqual(seeded.snapshot().lanterns[0].fuel,30)
assert.equal(seeded.snapshot().lanterns[0].relit_count,2)
const cheap=new Game(t,1,{...quiet,player:{carried:5},lanterns:[{id:'L1',pos:[0,0,0],ever_lit:true}]},1)
press(cheap)
assert.equal(cheap.score,65)
assert.equal(cheap.lanterns[0].relit_count,1)
const pulseDrain=new Game(t,1,{...quiet,player:{carried:3},lanterns:[{id:'L1',pos:[0,0,0],lit:true,fuel:20}],shades:[{id:'S1',pos:[0,.8,1],state:'drain',target_lantern_id:'L1'}]},1)
pulseDrain.step({...idle(),pulse:true})
assert.equal(pulseDrain.score,15)
assert.equal(pulseDrain.shades[0].state,'stunned')
const nearlyDawn=new Game(t,1,{...quiet,time_left_s:1/60,lanterns:[{id:'L1',lit:true},{id:'L2',lit:true}]},1)
nearlyDawn.step(idle())
assert.equal(nearlyDawn.state,'lost')
assert.equal(nearlyDawn.events.find(e=>e.name==='game_over')?.data.reason,'dawn')
console.log('PASS CP3 scenario, relight score, pulse drain and failed dawn')
const bunny=new Game(t,2,quiet,1)
bunny.step({...idle(),jump:true})
for(let tick=2;tick<=35;tick++)bunny.step(idle())
assert.equal(bunny.player.grounded,false)
const beforeBufferedJump=bunny.player.pos[1]
bunny.step({...idle(),jump:true})
for(let tick=37;tick<=44;tick++)bunny.step(idle())
assert.ok(bunny.player.grounded || bunny.player.pos[1]>beforeBufferedJump)
assert.ok(bunny.player.vel[1]>=0 || bunny.player.grounded)
console.log('PASS bunny hop buffers jump near landing without changing jump physics')
